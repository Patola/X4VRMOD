"""Name a dumped module by fingerprinting its DYNAMIC block against X4's XMLs.

    tools/name_module.py mod-0012 mod-0022      # detail for these
    tools/name_module.py                        # name every module it can
    tools/name_module.py --ambiguous            # only the ones it cannot pin

X4's shader modules carry no names, and the project has been identifying them
by an FNV-1a hash joined against `/tmp/x4vr-shaders` -- which says *which dump*
a module is, never *what it does*. This says what it does.

**How.** `BLOCK_BUFFER_BINDING_SLOT_DYNAMIC` (set 4 binding 0) has a fixed head
generated by the engine and a tail generated from the shader's OWN
`<properties>` list in `shadergl/ogl/*.xml`. So the tail member names ARE the
XML's property names, in order, with a type prefix -- a fingerprint that maps a
dump back to a source file. Expansion rules, read off the observed blocks:

    <float|int|bool name="X">  ->  U_X
    <float4 name="X">          ->  U_X
    <samp name="X">            ->  S_B_idx S_Bstr S_B_tiling S_B_tiling_v
                                   S_B_color,  where B is X without a
                                   trailing "_map" (common.glsl builds the
                                   sampler handle as B + "_map")

**Validated against a module identified independently.** `mod-0012` is the
present pass's fragment shader -- the layer names it in the log, it makes
exactly the two bindless samples `copy_gamma.frag.glsl` makes, and it is one of
only four modules declaring `U_fsr3g_useuitexture`. Its fingerprint matches
`copy_gamma.xml` EXACT and nothing else.

**Ambiguity is real and is reported, not hidden.** Two shaders with identical
property lists are indistinguishable here -- `visual_transition` and
`xu_simple_hdr_out` both expand to the same ten members. Break the tie on the
vertex stage: `drawfs.vert.glsl` uses only `gl_VertexIndex` (one OpEntryPoint
Vertex with no attribute interface), `simple.vert.glsl` takes real attributes.

**Coverage, so a blank is not read as a failure: 38 of 409 dumps named
uniquely, 24 ambiguous, 308 unmatched, 39 declaring no DYNAMIC block.** The
named ones are the post-process, present and UI shaders -- small property
lists, no macro-injected members -- which is the class every question about
the composite and the HUD lands in. The big material shaders do not match
because their blocks carry members generated by macros that the XML never
lists. UNMATCHED means "this fingerprint cannot pin it", never "not an X4
shader".

Egosoft's sources and dumps are `/tmp` only, never committed.
"""
import argparse
import glob
import os
import sys
import xml.etree.ElementTree as ET
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import block_offset_census as C

# Everything below this byte is the engine's fixed head (four texture
# matrices, the animation flag, the envmap probe block). The per-shader tail
# starts here. Recorded from the dumps, not predicted: the boundary is where
# every module stops agreeing.
PREFIX_END = 432


def expand(tag, name):
    if tag == 'samp':
        base = name[:-4] if name.endswith('_map') else name
        return [f'S_{base}_idx', f'S_{base}str', f'S_{base}_tiling',
                f'S_{base}_tiling_v', f'S_{base}_color']
    return [f'U_{name}']


def xml_names(path):
    """(dynamic-property members, static-property members) for one XML.

    X4 splits a shader's properties across two blocks: `dynamic="true"` ones
    go into the DYNAMIC block's tail, the rest into the MATERIAL block (set 2)
    from byte 0. Measured, not assumed -- mod-0038's MATERIAL block opens with
    `S_diffuse_idx` at byte 0 while its DYNAMIC tail holds only the overrides
    and the pattern layer.

    A shader with no MATERIAL block puts everything in DYNAMIC: `copy_gamma`
    declares `input_rt` without `dynamic` and it still lands in the tail. So
    the static list is matched only when the module HAS a material block.
    """
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError:
        return None
    props = root.find('properties')
    if props is None:
        return None
    dyn, static, allp = [], [], []
    for p in props:
        n = p.get('name')
        if not n:
            continue
        e = expand(p.tag, n)
        allp.extend(e)
        (dyn if p.get('dynamic') == 'true' else static).extend(e)
    return dyn, static, allp


def load_xmls(d):
    out = {}
    for p in sorted(glob.glob(os.path.join(d, '*.xml'))):
        v = xml_names(p)
        if v and v[2]:
            out[os.path.basename(p)] = v
    return out


def tail_of(path):
    """(DYNAMIC tail, MATERIAL members or None)."""
    r = C.analyse(path, 4, 0)
    if not r:
        return None, None
    members, _read, _b = r
    tail = [n for _i, n, off, _t in members
            if off is not None and off >= PREFIX_END]
    mat = C.analyse(path, 2, 0)
    matn = [n for _i, n, _o, _t in mat[0]] if mat else None
    return tail, matn


def match(tail, mat, xmls):
    """(exact, prefix, truncated) name lists, matched on the DYNAMIC tail.

    A module WITH a material block is matched against the `dynamic="true"`
    properties only; one without, against the whole list.

    **The material block is displayed but NOT cross-checked.** Requiring
    `static == mat` as well was tried and made coverage worse (22 unique ->
    20), because X4 injects members the XML never lists -- mod-0038's material
    block carries `U_deferred` and `U_smoothstr` from a macro. A stricter test
    that names fewer things is only better if the ones it drops were wrong,
    and that was not established, so the loose rule stands and this comment
    records the attempt.
    """
    exact, pre, trunc = [], [], []
    for f, (dyn, _static, allp) in xmls.items():
        want = dyn if mat is not None else allp
        if not want:
            continue
        if want == tail:
            exact.append(f)
        elif tail[:len(want)] == want:
            pre.append(f)
        elif want[:len(tail)] == tail:
            trunc.append(f)
    return exact, pre, trunc


def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument('modules', nargs='*', help='e.g. mod-0012 (default: all)')
    ap.add_argument('--ambiguous', action='store_true',
                    help='list only modules with 0 or >1 exact matches')
    ap.add_argument('--dumps', default='/tmp/x4vr-shaders')
    ap.add_argument('--ogl', default='/tmp/x4-shadersrc/shadergl/ogl')
    a = ap.parse_args()

    xmls = load_xmls(a.ogl)
    if not xmls:
        sys.exit(f'no .ogl XMLs in {a.ogl} -- run tools/extract_shaders.py')

    if a.modules:
        for m in a.modules:
            p = os.path.join(a.dumps, m + '.spv')
            tail, mat = tail_of(p)
            if tail is None:
                print(f'{m}: declares no set 4 binding 0 — cannot fingerprint')
                continue
            exact, pre, trunc = match(tail, mat, xmls)
            print(f'--- {m}: {len(tail)} tail member(s)')
            print(f'    dyn: {" ".join(tail)}')
            if mat is not None:
                print(f'    mat: {" ".join(mat)}')
            for f in sorted(exact):
                print(f'    EXACT      {f}')
            for f in sorted(pre):
                print(f'    PREFIX     {f}  (module has extra members)')
            for f in sorted(trunc):
                print(f'    TRUNCATED  {f}  (XML has extra properties)')
            if not (exact or pre or trunc):
                print('    no XML matches')
        return

    files = sorted(glob.glob(os.path.join(a.dumps, 'mod-*.spv')))
    stats = Counter()
    for p in files:
        m = os.path.basename(p)[:-4]
        tail, mat = tail_of(p)
        if tail is None:
            stats['no block'] += 1
            continue
        exact, pre, trunc = match(tail, mat, xmls)
        if len(exact) == 1:
            stats['unique'] += 1
            if not a.ambiguous:
                print(f'{m}  {exact[0]}')
        elif exact:
            stats['ambiguous'] += 1
            if a.ambiguous:
                print(f'{m}  AMBIGUOUS  {", ".join(sorted(exact))}')
        else:
            stats['unmatched'] += 1
            if a.ambiguous:
                near = sorted(pre + trunc)[:3]
                print(f'{m}  UNMATCHED  {len(tail)} members'
                      + (f'  near: {", ".join(near)}' if near else ''))
    print(f"\n{len(files)} dumps: {stats['unique']} uniquely named, "
          f"{stats['ambiguous']} ambiguous, {stats['unmatched']} unmatched, "
          f"{stats['no block']} declare no DYNAMIC block")


if __name__ == '__main__':
    main()
